export function getNotificationTitle(type: string, lang: Language): string {
  if (type === 'comment') return t(lang, 'comments.newCommentNotif');
  if (type === 'message') return t(lang, 'chat.newMessageNotif');
  return type;
}

export function getNotificationContent(notification: { type: string; content: string }, lang: Language): string {
  if (notification.type === 'comment') return t(lang, 'comments.commentedNotif', { name: notification.content });
  return notification.content;
}
